#!/usr/bin/env python3
"""Generate scripts/instance_catalog_data.py from dim_ec2_price seed + instance_specs.yml.

EC2 on-demand USD/hour is parsed from the in-repo dim_ec2_price.sql seed (sole pricing
authority).  Hardware specs (vCPU, RAM, family) come from instance_specs.yml.

Usage:
    uv run python scripts/generate_instance_catalog.py
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
DIM_EC2_PRICE_SQL = (
    REPO_ROOT
    / "dags/platform/enrich_databricks_pricing/queries/enrich/dim_ec2_price.sql"
)
INSTANCE_SPECS_YML = REPO_ROOT / "scripts/instance_specs.yml"
OUTPUT_PATH = REPO_ROOT / "scripts/instance_catalog_data.py"

_VALUES_TUPLE_RE = re.compile(
    r"\(\s*'([^']+)'\s*,\s*([0-9]+(?:\.[0-9]+)?)\s*\)"
)


def parse_dim_ec2_price_seed(sql_path: Path) -> dict[str, float]:
    """Parse on_demand_usd_hour tuples from dim_ec2_price.sql VALUES seed."""
    text = sql_path.read_text(encoding="utf-8")
    prices: dict[str, float] = {}
    for name, price_str in _VALUES_TUPLE_RE.findall(text):
        prices[name.lower()] = float(price_str)
    if not prices:
        raise ValueError(f"No EC2 price tuples found in {sql_path}")
    return prices


def load_instance_specs(yml_path: Path) -> dict[str, dict[str, object]]:
    data = yaml.safe_load(yml_path.read_text(encoding="utf-8"))
    instances = data.get("instances") or {}
    return {str(k).lower(): v for k, v in instances.items()}


def build_catalog(
    prices: dict[str, float],
    specs: dict[str, dict[str, object]],
) -> tuple[dict[str, dict[str, object]], dict[str, float]]:
    """Join specs × prices; warn on mismatches."""
    catalog: dict[str, dict[str, object]] = {}
    ec2_prices: dict[str, float] = {}

    for name, spec in sorted(specs.items()):
        price = prices.get(name)
        if price is None:
            print(f"WARNING: spec-only (no seed price): {name}", file=sys.stderr)
            continue
        catalog[name] = spec
        ec2_prices[name] = price

    for name in sorted(prices):
        if name not in specs:
            print(f"WARNING: seed-only (no sizing spec): {name}", file=sys.stderr)

    if not catalog:
        raise ValueError("No catalog entries — check instance_specs.yml and dim_ec2_price.sql")

    return catalog, ec2_prices


def render_output(
    catalog: dict[str, dict[str, object]],
    ec2_prices: dict[str, float],
) -> str:
    lines = [
        '"""Auto-generated by scripts/generate_instance_catalog.py — do not edit.',
        "",
        "INSTANCE_SPECS_RAW: vCPU/RAM/family per instance (from instance_specs.yml).",
        "EC2_ON_DEMAND_USD_PER_HOUR: on-demand USD/hr (from dim_ec2_price.sql seed).",
        '"""',
        "",
        "INSTANCE_SPECS_RAW: dict[str, dict[str, object]] = {",
    ]
    for name, spec in catalog.items():
        lines.append(
            f'    "{name}": {{"vcpus": {spec["vcpus"]}, '
            f'"memory_gb": {spec["memory_gb"]}, "family": "{spec["family"]}"}},'
        )
    lines.append("}")
    lines.append("")
    lines.append("EC2_ON_DEMAND_USD_PER_HOUR: dict[str, float] = {")
    for name, price in ec2_prices.items():
        lines.append(f'    "{name}": {price},')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT_PATH,
        help=f"Output Python module (default: {OUTPUT_PATH})",
    )
    args = parser.parse_args(argv)

    prices = parse_dim_ec2_price_seed(DIM_EC2_PRICE_SQL)
    specs = load_instance_specs(INSTANCE_SPECS_YML)
    catalog, ec2_prices = build_catalog(prices, specs)

    output = render_output(catalog, ec2_prices)
    args.output.write_text(output, encoding="utf-8")
    print(
        f"Wrote {len(catalog)} instance types to {args.output}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
