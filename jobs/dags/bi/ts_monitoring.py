def f_psi(train, prod, var_bins, ym, var_sum=None):
  
  # we cut the training set according to var_bins:
  out, train_bins = pd.qcut(train[var_bins], q=10, retbins=True, duplicates = 'drop')
  ym_subset = prod[prod.ym==ym]
  
  #if var_sum is not None, it means we want to analyse the distribution of its sum in each bin of var_bins
  if var_sum is not None:
    train_distrib = train[var_sum].groupby(out).sum()/float(train[var_sum].sum())
    ym_distrib = ym_subset[var_sum].groupby(pd.cut(ym_subset[var_bins], bins=train_bins, include_lowest=True)).sum()/float(ym_subset[var_sum].sum())
  #otherwise we simply analyses the distribution of var_bins
  else:    
    train_distrib = train[var_bins].groupby(out).count()/float(train.shape[0])
    ym_distrib = ym_subset[var_bins].groupby(pd.cut(ym_subset[var_bins], bins=train_bins, include_lowest=True)).count()/float(ym_subset.shape[0])
  
    
  psi_df = pd.concat([ym_distrib,train_distrib], axis=1)
  psi_df.columns = [ym,'train']
  psi_df['new-train'] = psi_df[ym] - psi_df.train
  psi_df['ln(new/train)'] = np.log(psi_df[ym]/psi_df.train)

  psi_df['ind'] = psi_df['new-train'] * psi_df['ln(new/train)']
  psi_df = psi_df[['train',    ym,    'new-train',    'ln(new/train)',    'ind']]
  
  return psi_df.ind.sum(), psi_df


