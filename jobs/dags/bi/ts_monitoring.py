    #we need to take the minimum date between:
    #- due date + t, for paid invoices that have a delay>=t
    candidates_all = (contract.loc[contract.delay>=t, 'tenant_due_date'] + pd.to_timedelta(t, unit='d')).tolist()
    thres_date = min(candidates_all) if len(candidates_all)>0 else np.nan
    
    #determine if there are any unpaid invoices for more than t days
    candidates_unpaid = (contract.loc[contract.tenant_status_is_open & (contract.delay>=t),'tenant_due_date'] + pd.to_timedelta(t, unit='d')).tolist()
    over_t = (len(candidates_unpaid)>0) # the current status is over t if there is any open invoice with delay above t

    #write in df:
    df_performance_threshold=df_performance_threshold.append({
        'contract_id':cid,
        'threshold':t,
        'date_ever':thres_date,
        'status_over':over_t
    }, ignore_index=True)

