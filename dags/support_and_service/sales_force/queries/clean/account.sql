    Id AS id_account,
    OwnerId AS id_owner,
    CreatedById AS id_created_by,
    LastModifiedById AS id_last_modified_by,
    MasterRecordId AS id_master_record,
    RecordTypeId AS id_record_type,
    ParentId AS id_parent,
    JigsawCompanyId AS jigsaw_company_id,
    CustomerId__c AS id_customer,
    ExternalId__c AS id_external,
    Name AS account_name,
    Type AS account_type,
    BillingStreet AS billing_street,
    BillingCity AS billing_city,
    BillingState AS billing_state,
    BillingPostalCode AS billing_postal_code,
    BillingCountry AS billing_country,
    BillingLatitude AS billing_latitude,
    BillingLongitude AS billing_longitude,
    BillingGeocodeAccuracy AS billing_geocode_accuracy,
    BillingAddress AS billing_address,
