    Rating AS rating,
    Site AS site,
    SystemModstamp AS system_mod_stamp,
    SourceSystemIdentifier AS source_system_identifier,
    Jigsaw AS jigsaw,
    AccountSource AS account_source,
    SicDesc AS sic_desc,
    Email__c AS email,
    IsDeleted AS is_deleted,
