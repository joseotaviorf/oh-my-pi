    Id AS id,
    et4ae5__Contact__c AS id_contact,
    CreatedById AS id_created_by,
    LastModifiedById AS id_last_modified_by,
    et4ae5__Lead__c AS id_lead,
    OwnerId AS id_owner,
    et4ae5__SendDefinition__c AS id_send_definition,
    et4ae5__TriggeredSendDefinition__c AS id_triggered_send_definition,
    et4ae5__CampaignMemberId__c AS campaign_member_id,
    et4ae5__Contact_ID__c AS contact_id,
    CurrencyIsoCode AS currency_iso_code,
    et4ae5__Email__c AS email,
    et4ae5__Email_Asset_ID__c AS email_asset_id,
    et4ae5__Email_ID__c AS email_id,
    et4ae5__FromAddress__c AS from_address,
    et4ae5__FromName__c AS from_name,
    et4ae5__Lead_ID__c AS lead_id,
