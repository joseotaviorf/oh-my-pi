    id AS id_backoffice_record,
    channel AS id_channel,
    uniqueId AS id_contact,
    tableId AS id_table,
    campaignId AS id_campaign,
    agentId AS id_agent,
    lineMailingId AS id_line_mailing,
    businessId AS id_business,
    mailingId AS id_mailing,
