    COALESCE(GET_JSON_OBJECT(event_properties, '$.rent_properties_statuses'),GET_JSON_OBJECT(event_properties, '$.rent_properties_status')) AS ep_rent_house_status,
    COALESCE(GET_JSON_OBJECT(event_properties, '$.sale_properties_statuses'),GET_JSON_OBJECT(event_properties, '$.sale_properties_status')) AS ep_sale_house_status,
    city,
    country,
    data,
    device_brand,
    device_carrier,
    device_family,
    device_manufacturer,
    device_model,
    device_type,
    dma,
    ip_address,
    location_lat,
    location_lng,
    os_name,
    os_version,
    platform,
    library,
    region,
    start_version,
    language,
    version_name,
    sample_rate,
    event_properties,
    user_properties,
    is_paying,
    is_attribution_event,
    ts_server_received,
    ts_event,
    ts_server_uploaded,
    ts_user_created,
    ts_client_event,
    ts_client_uploaded,
    ts_processed,
    year,
    month,
    day
