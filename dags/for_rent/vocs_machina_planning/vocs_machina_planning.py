"""
VOCS-34 Slice 1 -- raw inference-status collector for vocs-machina.

Hand-rolled DAG: intentionally NOT generated by the DAG Builder / a
*_declaration.yml (unlike dags/for_rent/vocs_machina, which this DAG reads
from but never modifies). A later slice (Slice 3) needs
airflow.timetables.datasets.DatasetOrTimeSchedule combined with
airflow.timetables.trigger.CronTriggerTimetable to express a hybrid
cron+dataset schedule. BaseWorkflow cannot express that: it treats
schedule_interval and dataset_dependencies as mutually exclusive (see
packages/bietlejuice-airflow/src/bietlejuice/base/airflow/dag_builders/main_builder/workflows/base_workflow.py,
around lines 107-132). So this DAG is hand-rolled from the first commit
instead of being upgraded later. Placeholder schedule only in this slice
(schedule_interval=None) -- the hybrid DatasetOrTimeSchedule is explicitly
out of scope here.

What this DAG does:
  1. stage-inference-status-to-s3 (PythonOperator): reads quintoml's prompt
     manifest, works out which (day, prompt_id, prompt_hash) backfill
     partitions should exist, checks whether quintoml has finalized each one
     (_SUCCESS marker present), and stages a done/missing snapshot as JSON to
     this repo's own datalake bucket.
  2. create-cluster -> load-vocs-machina-inference-status-raw ->
     terminate-cluster: a Databricks cluster loads that JSON into
     datalake_vocs_machina_planning_raw.vocs_machina_inference_status.

Style model: dags/fintech/enrich_dai_report/enrich_dai_report.py (manual
DAG()/create-cluster/submit-run/terminate-cluster wiring) and
dags/platform/dag_inventory/dag_inventory.py (PythonOperator + S3Hook
staging a JSON blob to S3 ahead of the Spark job).
"""

