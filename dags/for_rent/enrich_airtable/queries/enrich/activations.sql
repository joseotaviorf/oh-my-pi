WITH activations_last_version AS (
    SELECT
        ROW_NUMBER() OVER(PARTITION BY cpf ORDER BY ts_updated DESC) AS ordered_version,
        id_activations,
        id_airtable_record,
        activation_status,
        actuation_state,
        agent_complete_name,
        agent_creci,
        agent_email,
        agent_phone_number,
        chosen_region,
        cpf,
        giving_up_reason,
        model,
        original_lead,
        region,
        region_first_option,
        region_second_option,
        has_activation_notification,
        has_welcome_email,
        has_whats_pocket,
        dt_agency_confirmation,
        dt_birth,
        dt_contract_sent,
        dt_giving_up,
        dt_id_creation,
        dt_jitex_requested,
        dt_kit_received,
        dt_signed,
        dt_week_accreditated,
        ts_updated,
        year,
        month,
        day
    FROM
        datalake_airtable_clean.activations
)
SELECT
    id_activations,
    id_airtable_record,
    activation_status,
    actuation_state,
    agent_complete_name,
    agent_creci,
    agent_email,
    agent_phone_number,
    chosen_region,
    cpf,
    giving_up_reason,
    model,
    original_lead,
    region,
    region_first_option,
    region_second_option,
    has_activation_notification,
    has_welcome_email,
    has_whats_pocket,
    dt_agency_confirmation,
    dt_birth,
    dt_contract_sent,
    dt_giving_up,
    dt_id_creation,
    dt_jitex_requested,
    dt_kit_received,
    dt_signed,
    dt_week_accreditated,
    ts_updated,
    year,
    month,
    day
FROM
    activations_last_version
WHERE
    ordered_version = 1