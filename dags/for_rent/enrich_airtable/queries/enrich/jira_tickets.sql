WITH tickets_last_version AS (
    SELECT
        ROW_NUMBER() OVER(PARTITION BY id_issue ORDER BY ts_updated DESC) ordered_version,
        id_agent,
        id_airtable_record,
        id_ql_agent,
        id_issue,
        activated,
        cpf,
        description,
        open_in_jira,
        permanent_deaccreditation,
        ql_agent_complete_name,
        ql_agent_line,
        ql_agent_region,
        ql_agent_type,
        ql_deaccreditation_reason,
        ql_solicitation_type,
        ql_suspension_type,
        responsible,
        summary,
        dt_begin,
        dt_deaccreditated,
        dt_deaccreditation_return,
        dt_end,
        ts_created,
        ts_updated,
        year,
        month,
        day
    FROM
        datalake_airtable_clean.jira_tickets
)
SELECT
    id_agent,
    id_airtable_record,
    id_ql_agent,
    id_issue,
    activated,
    cpf,
    description,
    open_in_jira,
    permanent_deaccreditation,
    ql_agent_complete_name,
    ql_agent_line,
    ql_agent_region,
    ql_agent_type,
    ql_deaccreditation_reason,
    ql_solicitation_type,
    ql_suspension_type,
    responsible,
    summary,
    dt_begin,
    dt_deaccreditated,
    dt_deaccreditation_return,
    dt_end,
    ts_created,
    ts_updated,
    year,
    month,
    day
FROM
    tickets_last_version
WHERE
    ordered_version = 1