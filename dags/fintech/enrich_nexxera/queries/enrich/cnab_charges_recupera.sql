SELECT DISTINCT
    id_bank,
    id_document_type,
    recupera_creditor_name,
    bank_agency,
    bank_account,
    account_verification_digit,
    cpf_cnpj,
    company_use,
    our_number,
    document_number,
    payers_name,
    occurrence_code,
    occurrence_code_description,
    file_name,
    ROW_NUMBER() OVER (PARTITION BY our_number ORDER BY year, month, day, file_name_sulfix) AS payment_attempts,
    IF(ROW_NUMBER() OVER (PARTITION BY our_number ORDER BY year DESC, month DESC, day DESC, file_name_sulfix DESC) = 1, TRUE, FALSE) AS is_latest_attempt,
    due_amount,
    interest_amount,
    net_amount,
    billing_fee_amount,
    iof_amount,
    rebate_amount,
    discount_amount,
    others_credit_amount,
    dt_due,
    dt_credit,
    dt_occurrence_code,
    ts_ingested,
    year,
    month,
    day
FROM
    df
