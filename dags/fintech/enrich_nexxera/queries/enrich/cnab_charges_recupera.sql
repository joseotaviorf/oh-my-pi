            WHEN OCCURRENCE_CODE = '39' THEN 'TARIFA DE OCORRÊNCIAS'
            WHEN OCCURRENCE_CODE = '40' THEN 'TARIFA MENSAL DE EMISSÃO DE BOLETO/TARIFA MENSAL DE ENVIO DE DUPLICATA'
