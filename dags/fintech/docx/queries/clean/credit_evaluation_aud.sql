SELECT
    id AS id_credit_evaluation,
    proposal_id AS id_proposal,
    house_id AS id_house,
    user_id AS id_user,
    city_id AS id_city,
    group_id AS id_group,
    CAST(get_json_object(early_result, '$[0].analysisRequestId') AS BIGINT) AS analysis_request_id,
    rev,
    revtype AS rev_type,
    status,
    scope,
    limit_value,
    proponent_group_type,
    result,
    get_json_object(early_result, '$[0].guaranteeType') AS early_result_guarantee_type,
    CAST(get_json_object(early_result, '$[0].guaranteeFactor') AS INTEGER) AS guarantee_factor,
    CAST(get_json_object(early_result, '$[0].preApprovedLimit') AS DECIMAL(10,2)) AS pre_approved_limit,
    reason,
    early_result,
    automatic AS is_automatic,
    type,
    revend AS rev_end,
    user_id_mod AS mod_id_user,
    status_mod AS mod_status,
    result_mod AS mod_result,
    reason_mod AS mod_reason,
    early_result_mod AS mod_early_result,
    proponent_group_type_mod AS mod_proponent_group_type,
    limit_value_mod AS mod_limit_value,
    expires_at_mod AS mod_ts_expires,
    city_id_mod AS mod_city_id,
    automatic_mod AS mod_is_automatic,
    type_mod AS mod_type,
    expires_at AS ts_expires
FROM
    datalake_docx_raw.credit_evaluation_aud
