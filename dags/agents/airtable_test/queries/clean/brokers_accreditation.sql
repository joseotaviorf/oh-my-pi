    id AS id_airtable_record,
    CAST(inscricao AS BIGINT) AS id_inscription,
    CAST(ticket_da_indicacao_novo_forms_sale AS BIGINT) AS id_broker_referral_ticket,
    CAST(id_admin AS BIGINT) AS id_admin,
    CAST(cpf AS BIGINT) AS cpf,
    nome_completo AS full_name,
    preferencia_de_atuacao AS performance_preference,
    2_opcao AS second_option,
    etapa_processo AS stage_process,
    depara_regiao AS region_from_to,
    estado_de_atuacao AS state_operation,
    situacao_cadastro AS registration_status,
    status_parceiro AS partner_status,
    aprovado_inscricao AS registration_approved,
    aprovado_batepapo AS chat_approved,
    motivo_reprovacao AS disapproval_reason,
    classificacao_entrevista AS interview_classification,
    tipo_do_cadastro AS registration_type,
