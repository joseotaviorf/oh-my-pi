    CAST(score_entrevista AS INTEGER) AS score_interview,
    CAST(score_ocupacao AS INTEGER) AS score_occupation,
    CAST(score_autonomo AS INTEGER) AS score_autonomous,
    CAST(score_experiencia AS INTEGER) AS score_experience,
    CAST(score_captacao AS INTEGER) AS score_capture,
    CAST(score_disponibilidade_semana AS INTEGER) AS score_availability_week,
    CAST(score_disponibilidade_final_de_semana AS INTEGER) AS score_availability_end_of_week,
    CAST(score_pre_visita AS INTEGER) AS score_before_visit,
    CAST(score_visita AS INTEGER) AS score_visit,
