    DATE(data_de_assinatura_de_contrato) AS dt_contract_signed,
    DATE(data_de_cadastro_admin) AS dt_admin_registered,
    DATE(data_de_vinculo_teams) AS dt_teams_link_created,
    DATE(data_envio_de_onboarding) AS dt_onboarding_sent,
    DATE(data_de_ativacao_novo_fluxo) AS dt_activated,
    DATE(data_finalizacao_de_onboarding) AS dt_onboarding_completed,
    DATE(abertura_de_agenda) AS dt_agenda_opened,
    DATE(data_de_nascimento) AS dt_birth,
    DATE(data_de_inscricao) AS dt_registration,
    TIMESTAMP(puxar_para_entrevista) AS ts_interview_scheduled,
    TIMESTAMP(createdTime) AS ts_airtable_record_created,
    MAKE_DATE(year, month, day) AS dt_load,
    year,
    month,
    day
FROM
    datalake_airtable_test_raw.brokers_accreditation
WHERE
    year = {year}
    AND month = {month}
    AND day = {day}