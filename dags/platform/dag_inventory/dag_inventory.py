"""
This .py file is not generated by the DAG Builder, because there are some tasks that run on Airflow that need to be added
before the Spark job is executed. Still, we use the RawCustomIngestionWorkflow and modify the resulting DAG.
"""

import json
import re
from datetime import datetime

from airflow.hooks.S3_hook import S3Hook
from airflow.models import DAG, DagBag
from airflow.operators.python_operator import PythonOperator

from bietlejuice.base.airflow.dag_builders.main_builder.factories.factory_dispatcher import (
    FactoryDispatcher,
)
from bietlejuice.base.airflow.enums.storage_format_enum import StorageFormatEnum
from bietlejuice.base.pipeline.layer_enum import LayerEnum
from bietlejuice.services.configuration_service import ConfigurationService

# Regex to identify the task that initializes the cluster
# Matches create-cluster, execute-job-cluster, create-cluster-1, execute-job-cluster-1, etc.
INIT_CLUSTER_REGEX = r"^(?:create|execute-job)-cluster(?:-\d+)?$"

# Pipeline inputs
SOURCE = "dag_inventory"
DAG_ID = f"bietlejuice.{SOURCE}"
config_service = ConfigurationService(SOURCE)

datalake_bucket = config_service.get_config("datalake_bucket")
dw_bucket = config_service.get_config("dw_bucket")

dag_declaration = {
    "dag": {
        "name": SOURCE,
        "owner": "Data Life Cycle",
        "schedule_interval": "10 21 * * *",
        "documentation": {
            "dag_purpose": "Retrieves data from a DagBag, such as cluster configs and tables generated."
        },
    },
    "workflow": {
        "layer": "raw",
        "type": "custom_ingestion",
        "load_spark_job": "load_dag_inventory_raw",
        "spark_job_arguments": [
            "{environment}",
            datalake_bucket,
            dw_bucket,
            "{dag_name}",
            "{table_name}",
            "{load_start_date}",
        ],
        "default_extraction_type": "incremental",
        "default_partitions": ["year", "month", "day"],
        "tables_customization": {"dag": {}, "table": {}},
    },
    "cluster": {
        "type": "consolidation_s_general_cluster",
        "custom_configurations": {"num_workers": 3},
    },
}
factory = FactoryDispatcher(layer=LayerEnum.RAW).get_factory(
    dag_args=dag_declaration["dag"],
    workflow_args=dag_declaration["workflow"],
    cluster_args=dag_declaration["cluster"],
)
dag_workflow = factory.get_workflow()
dag = dag_workflow.build_dag()


def get_init_cluster_task_name(dag: DAG) -> str:
    """Returns the name of the task that initializes the cluster."""
    for task in dag.task_ids:
        if re.match(INIT_CLUSTER_REGEX, task):
            return task
    return None


def find_dag_configs(dag_bag: DagBag) -> list:
    """Returns a list of dictionaries containing the DAG name, location and cluster configuration."""

    dag_configs = []
    for dag_name, dag in dag_bag.dags.items():
        init_cluster_task = get_init_cluster_task_name(dag)
        if not init_cluster_task:
            continue

        create_cluster = dag.get_task(init_cluster_task)
        dag_configs.append(
            {
                "dag": dag_name,
                "dag_location": dag.filepath,
                "cluster_configuration": create_cluster.cluster_configuration,
            }
        )
    return dag_configs


def find_tables_generated_by_dag(dag_bag: DagBag) -> dict:
    """
    Returns a dictionary containing the tables generated by the DAG.
    In order to do that, it finds all the sync_metadata tasks. We can extract its parameters to find the table name,
    bucket, and other parameters, since it is standardized across all DAGs.
    """
    mapping = []
    for dag_name, dag in dag_bag.dags.items():
        if not get_init_cluster_task_name(dag):
            continue
        for task in dag.tasks:
            if not task.params or "table_name" not in task.params:
                continue
            load_task_name = task.task_id
            mapping.append(
                {
                    "dag": dag_name,
                    "task": load_task_name,
                    "database": task.params.get("schema", "").lower() or None,
                    "table": task.params.get("table_name", "").lower() or None,
                    "layer": task.params.get("layer"),
                    "transformation_grade": task.params.get("transformation_grade"),
                    "bucket": task.params.get("bucket"),
                    "is_delta": task.params.get("storage_format")
                    == StorageFormatEnum.DELTA.value,
                }
            )
    return mapping


def extract_table_to_s3(table_name: str, load_start_date: str, **kwargs) -> None:
    """Collects data from the DagBag and extracts it to S3."""

    dag_bag = DagBag(store_serialized_dags=True, include_examples=False)
    dag_bag.collect_dags_from_db()
    extract_functions = {"dag": find_dag_configs, "table": find_tables_generated_by_dag}
    if table_name not in extract_functions:
        raise KeyError(f"{table_name} does not have an extraction function configured.")

    table_data = extract_functions.get(table_name)(dag_bag)
    hook = S3Hook(aws_conn_id="aws_default")
    execution_date = datetime.strptime(load_start_date, "%Y-%m-%d")
    partition_path = f"year={execution_date.year}/month={execution_date.month}/day={execution_date.day}"
    hook.load_string(
        string_data=json.dumps(table_data),
        key=f"raw/dag_inventory/dag_bag_content/{table_name}/{partition_path}/{table_name}.json",
        bucket_name=datalake_bucket,
        replace=True,
        acl_policy="bucket-owner-full-control",
    )


def create_extraction_task(table_name: str) -> PythonOperator:
    return PythonOperator(
        dag=dag,
        task_id=f"extract-{table_name}-from-dagbag-to-s3",
        python_callable=extract_table_to_s3,
        op_kwargs={
            "table_name": table_name,
            "load_start_date": "{{ get_date_param(dag_run, data_interval_start | ds, 'load_start_date') }}",
        },
        provide_context=True,
    )


execute_job_cluster_task = dag.get_task("execute-job-cluster")

for table_name in dag_declaration["workflow"]["tables_customization"]:
    task = create_extraction_task(table_name)
    task >> execute_job_cluster_task
