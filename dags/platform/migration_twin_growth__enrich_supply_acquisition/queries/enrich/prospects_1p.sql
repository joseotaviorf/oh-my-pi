WITH lead_rejection AS (
  SELECT 
    id_house_lead AS id_lead, 
    business_context,  
    reason, 
    ts_created
  FROM 
    datalake_rene_descartes_clean.lead_rejection
  WHERE 
    COALESCE(origin, 'LEAD') != 'PROSPECT' -- Only discards generated by Rene
),
wololo_tag AS (
  SELECT 
    id AS id_wololo, 
    id_reference AS id_lead_ebdb,
    LOWER(sales_company) AS ops_assigned
  FROM 
    datalake_wololo_clean.prospect
  GROUP BY 1, 2, 3
),
olos_tag AS (
  SELECT
    id_lead AS id_lead_ebdb,
    LOWER(
      CASE 
        WHEN LOWER(om.sales_company) = 'actionline' THEN 'action_line'
        ELSE om.sales_company
      END
    ) AS ops_assigned
  FROM
    datalake_olos_dialer.outbound_mailing AS om
  QUALIFY ROW_NUMBER() OVER (PARTITION BY om.id_lead ORDER BY om.ts_created) = 1
),
olos_contact_tag AS (
  SELECT
    id_lead AS id_lead_ebdb,
    LOWER(      
      CASE 
        WHEN LOWER(om.sales_company) = 'actionline' THEN 'action_line'
        ELSE om.sales_company
      END
    ) AS ops_assigned
  FROM
    datalake_olos_dialer.outbound_last_contact AS om
  WHERE 
    om.id_lead != -1
      AND om.id_lead IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY om.id_lead ORDER BY om.ts_call_started) = 1
),
conversion AS (
  SELECT 
    id_lead, 
    business_context,
    MIN(id_house) AS id_house, 
    MAX(has_listing) AS has_listing,
    MAX(has_draft) AS has_draft,
    FIRST_VALUE(supply_source) AS supply_source
  FROM 
    datalake_supply_flows.conversion_lookup
  GROUP BY 1, 2
),
base AS (
  SELECT 
    l.sk_supply_lead,
    l.id_lead, 
    l.business_context,
    l.id_lead_ebdb,
    l.supply_source,
    l.id_region,
    l.id_referred_by,
    COALESCE(hla.status, 'NEW') AS status,
    r.dt_rev AS ts_event,
    r.rev,
    lr.business_context AS context_discards,
    lr.reason,
    lr.ts_created AS ts_discard
  FROM 
    datalake_supply_flows.leads_1p AS l
  LEFT JOIN 
    datalake_rene_descartes_clean.house_lead_aud AS hla
      ON (l.id_lead = hla.id)
  LEFT JOIN 
    lead_rejection AS lr
      ON (l.id_lead = lr.id_lead)
        AND (l.business_context = lr.business_context)
  LEFT JOIN 
    datalake_rene_descartes_clean.revinfo AS r
      ON hla.rev = r.rev
  QUALIFY ROW_NUMBER() OVER (PARTITION BY l.id_lead, l.business_context ORDER BY r.dt_rev) = 1
),
prospects_staging_1p AS (
    SELECT 
    b.sk_supply_lead,
    b.id_lead_ebdb,
    b.business_context,
    b.id_lead,
    b.id_region,
    b.id_referred_by,
    w.id_wololo,
    cl.id_house AS id_house,
    b.status,
    b.reason,
    cl.has_listing AS lead_has_listing,
    cl.has_draft AS lead_has_draft,
    IF(cl.has_listing OR cl.has_draft, TRUE, FALSE) AS lead_has_conversion,
    IF(b.ts_discard IS NOT NULL, TRUE, FALSE) AS lead_has_discard,
    IF(w.id_wololo IS NOT NULL, TRUE, FALSE) AS lead_has_wololo,
    CASE
        WHEN w.ops_assigned = 'olos' AND ot.ops_assigned IS NOT NULL 
        THEN ot.ops_assigned
        WHEN w.ops_assigned = 'olos' AND oct.ops_assigned IS NOT NULL
        THEN oct.ops_assigned
        ELSE w.ops_assigned
    END AS ops_assigned,
    b.ts_discard AS ts_discard,
    b.ts_event
    FROM base AS b
    LEFT JOIN wololo_tag AS w
        ON (b.id_lead_ebdb = w.id_lead_ebdb)
    LEFT JOIN olos_tag AS ot
        ON (b.id_lead_ebdb = ot.id_lead_ebdb)
    LEFT JOIN olos_contact_tag AS oct
        ON (b.id_lead_ebdb = oct.id_lead_ebdb)
    LEFT JOIN conversion AS cl
        ON (b.id_lead_ebdb = cl.id_lead)
        AND (b.supply_source = cl.supply_source)
        AND (b.business_context = cl.business_context)
),
converted_leads AS (
    SELECT   
      sk_supply_lead, 
      business_context,
      id_lead,
      'conversion_l2p' AS business_event,
      'PROSPECT' AS funnel_step,
      '1P' AS supply_source,
      CAST(NULL AS STRING) AS drop_step_reason,
      2 AS funnel_level,
      id_region,
      id_lead_ebdb,
      id_referred_by,
      id_wololo,
      id_house,
      ops_assigned,
      status AS aux_product_status,
      ts_event,
      CURRENT_TIMESTAMP AS ts_load
    FROM 
      prospects_staging_1p
    WHERE 
      (lead_has_conversion IS TRUE)
      OR (lead_has_discard IS FALSE)
),
discarded_leads AS (
    SELECT 
        sk_supply_lead,
        business_context,
        id_lead,
        'drop_l2p' AS business_event,
        'LEAD' AS funnel_step,
        '1P' AS supply_source,
        reason AS drop_step_reason,
        2 AS funnel_level,
        id_region,
        id_lead_ebdb,
        id_referred_by,
        id_wololo,
        id_house,
        ops_assigned,
        status AS aux_product_status,
        ts_event,
        CURRENT_TIMESTAMP AS ts_load -- TIMEZONE 00h
    FROM 
        prospects_staging_1p
    LEFT ANTI JOIN 
      converted_leads
    USING(sk_supply_lead, business_context)
),
final_attribution AS (
  SELECT *
  FROM converted_leads
  UNION ALL
  SELECT *
  FROM discarded_leads
)

SELECT 
  sk_supply_lead,
  business_context,
  id_lead,
  id_lead_ebdb,
  id_referred_by,
  id_region,
  id_wololo,
  id_house,
  business_event,
  funnel_step,
  supply_source,
  drop_step_reason,
  funnel_level,
  ops_assigned,
  aux_product_status,
  ts_event,
  ts_load
FROM final_attribution