SELECT
    evaluation_id AS id_evaluation,
    business_group_id AS id_business_group,
    template_defn_id AS id_template_definition,
    tmpl_period_id AS id_template_period,
    worker_id AS id_person,
    manager_id AS id_manager,
    assignment_id AS id_assignment,
    locked_by_user_id AS id_person_locked_performance,
    manager_assignment_id AS id_manager_assignment,
    review_period_id AS id_review_period,
    action_performed_by AS id_person_action_performed_by,
    template_type_code,
    language_code,
    status_code,
    prev_status_code AS previous_status_code,
    created_by,
    last_updated_by AS updated_by,
    action_code,
    action_reason,
    CAST(object_version_number AS INT) AS object_version_number,
    CAST(total_min_participants AS INT) AS min_total_participants,
    CAST(total_max_participants AS INT) AS max_total_participants,
    use_calc_ratings_flag = 'Y' AS is_calculated_ratings_used,
    calculation_ratings_flag = 'Y' AS is_rating_calculation_enabled,
    wrk_see_mgr_pcpn_flag = 'Y' AS is_worker_allowed_to_see_manager_participants,
    show_pcpn_calc_rating_flag = 'Y' AS is_participant_allowed_to_see_calculated_rating,
    show_mgr_calc_rating_flag = 'Y' AS is_manager_calculated_rating_shown,
    show_wkr_calc_rating_flag = 'Y' AS is_worker_calculated_rating_shown,
    show_mm_calc_rating_flag = 'Y' AS is_matrix_manager_allowed_to_see_calculated_rating,
    pcpn_feedback_req_flag = 'Y' AS is_feedback_required_for_participants,
    use_wrk_connections_flag = 'Y' AS is_worker_connections_used,
    CAST(start_date AS DATE) AS dt_performance_document_started,
    CAST(end_date AS DATE) AS dt_performance_document_ended,
    CAST(evaluation_date AS DATE) AS dt_evaluation_occurred,
    CAST(creation_date AS TIMESTAMP) AS ts_created,
    CAST(last_update_date AS TIMESTAMP) AS ts_updated,
    CAST(action_performed_date AS TIMESTAMP) AS ts_action_performed,
    NOW() AS ts_load,
    year,
    month,
    day
FROM
    datalake_pin_performance_raw.hra_evaluations
