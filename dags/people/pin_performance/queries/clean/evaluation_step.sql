SELECT
    eval_step_id AS id_evaluation_step,
    business_group_id AS id_business_group,
    evaluation_id AS id_evaluation,
    eval_participant_id AS id_evaluation_participant,
    parent_step_id AS id_parent_step,
    step_upd_action_performed_by AS id_person_performed_step_update,
    step_completed_by AS id_person_completed_step,
    action_performed_by AS id_person_responsible_for_action,
    step_code,
    step_status,
    step_sub_status,
    action_reason,
    step_upd_action_code AS update_action_code,
    created_by,
    last_updated_by AS updated_by,
    CAST(sequence_number AS INT) AS step_sequence_number,
    CAST(critical_alert_days AS INT) AS days_before_critical_alert,
    CAST(standard_alert_days AS INT) AS days_before_standard_alert,
    CAST(object_version_number AS INT) AS object_version_number,
    CAST(due_date AS DATE)  AS dt_due,
    CAST(creation_date AS TIMESTAMP) AS ts_created,
    CAST(last_update_date AS TIMESTAMP) AS ts_updated,
    CAST(step_completion_date AS TIMESTAMP) AS ts_step_completed,
    CAST(action_performed_date AS TIMESTAMP) AS ts_action_performed,
    CAST(step_upd_action_performed_date AS TIMESTAMP) AS ts_step_action_performed,
    NOW() AS ts_load,
    year,
    month,
    day
FROM
    datalake_pin_performance_raw.hra_eval_steps
