SELECT
    eval_participant_id AS id_eval_participant,
    business_group_id AS id_business_group,
    evaluation_id AS id_evaluation,
    person_id AS id_person,
    eval_role_id AS id_eval_role,
    questionnaire_id AS id_questionnaire,
    added_by_person_id AS id_added_by_person,
    notified_by_person_id AS id_notified_by_person,
    action_performed_by,
    role_type_code,
    participation_status_code,
    added_by_role,
    notified_by_role,
    created_by,
    last_updated_by AS updated_by,
    action_code,
    action_reason,
    notified_flag = 'Y' AS is_notified,
    fdback_started_flag = 'Y' AS is_feedback_started,
    locked_out_flag = 'Y' AS is_locked_out,
    CAST(object_version_number AS INT) AS object_version_number,,
    CAST(due_date AS DATE) AS dt_due,
    CAST(locked_out_date AS DATE) AS dt_lockout,
    CAST(status_update_date AS TIMESTAMP) AS ts_status_updated,
    CAST(fdback_completion_date AS TIMESTAMP) AS ts_feedback_completed,
    CAST(creation_date AS TIMESTAMP) AS ts_created,
    CAST(last_update_date AS TIMESTAMP) AS ts_updated,
    CAST(action_performed_date AS TIMESTAMP) AS ts_action_performed,
    NOW() AS ts_load,
    year,
    month,
    day
FROM
    datalake_pin_performance_raw.hra_eval_participants
