    SalaryId AS id_salary,
    AssignmentId AS id_assignment,
    SalaryBasisId AS id_salary_basis,
    AssignmentNumber AS assignment_number,
    ActionId AS id_action,
    ActionReasonId AS id_action_reason,
    GradeId AS id_grade,
    LegislativeDataGroupId AS id_legislative_data_group,
    SalaryFrequencyCode AS salary_frequency_code,
    SalaryBasisType AS salary_basis_type,
    CurrencyCode AS currency_code,
    quartile,
    quintile,
    FrequencyName AS frequency_name,
    DisplayName AS display_name,
    ActionCode AS action_code,
    ActionReasonCode AS action_reason_code,
    ActionReason AS action_reason,
    ActionName AS action_name,
    code AS salary_basis_code,
    LegalEmployerName AS legal_employer_name,
    GradeLadderName AS grade_ladder_name,
    GradeName AS grade_name,
    GradeStepName AS grade_step_name,
    GeographyName AS geography_name,
    GeographyTypeName AS geography_type_name,
    LastUpdatedBy AS last_update_by,
