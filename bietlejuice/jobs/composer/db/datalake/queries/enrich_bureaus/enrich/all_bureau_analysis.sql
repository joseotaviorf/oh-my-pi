  transunion.transunion_has_household_gt_high_school,
  transunion.transunion_has_household_qsa,
  transunion.transunion_has_high_income_class,
  transunion.transunion_has_household_gt_graduate,
  transunion.transunion_has_bolsa_familia
FROM
  (
    SELECT
      p.id_proposal,
      p.id AS id_proponent,
      CAST(REPLACE(REPLACE(cpf,".",""),"-","") AS BIGINT) AS cpf
    FROM
      datalake_sorting_hat_clean.proponent AS p
  ) AS proponent
LEFT JOIN
  datalake_bureaus.serasa_bureau_analysis AS serasa
    ON proponent.id_proposal = serasa.id_proposal
    AND proponent.id_proponent = serasa.id_proponent
    AND proponent.cpf = serasa.cpf 
LEFT JOIN
  datalake_bureaus.neoway_bureau_analysis AS neoway
    ON proponent.id_proposal = neoway.id_proposal
    AND proponent.cpf = neoway.cpf
LEFT JOIN
  datalake_bureaus.bigdatacorp_bureau_analysis AS bigdatacorp
    ON proponent.id_proposal = bigdatacorp.id_proposal
    AND proponent.id_proponent = bigdatacorp.id_proponent
    AND proponent.cpf = bigdatacorp.cpf
LEFT JOIN
  datalake_bureaus.transunion_bureau_analysis AS transunion
    ON proponent.id_proposal = transunion.id_proposal
    AND proponent.id_proponent = transunion.id_proponent
    AND proponent.cpf = transunion.cpf
WHERE
  proponent.id_proposal IS NOT NULL
  AND proponent.id_proponent IS NOT NULL
  AND proponent.cpf IS NOT NULL