from airflow.models import DAG, DagBag
from airflow.models.baseoperator import BaseOperator
from bietlejuice.base.pipeline import LayerEnum
from bietlejuice.base.db import MetastoreMappingFactory


class DagBagService:
    """
    This class is responsible for operations in bietlejuice that require DagBag manipulation. For example,
    finding all tasks that load to the datalake or DW, or mapping tables to their load tasks.
    """

    def __init__(self, dag_bag: DagBag, collect_from_database: bool) -> None:
        self.dag_bag = dag_bag
        if collect_from_database:
            self.dag_bag.collect_dags_from_db()
        self.dags = self.dag_bag.dags

    def find_all_non_scheduled_dags(self) -> list:
        """Returns a list of all DAGs that are not scheduled."""

        non_scheduled_dags = []
        for dag_name, dag in self.dag_bag.dags.items():
            if dag.schedule_interval is None:
                non_scheduled_dags.append(dag_name)
        return non_scheduled_dags

    def find_all_static_dags(self, dependencies: dict) -> list:
        """
        Given a dictionary of dependencies in the format
        {
            "dependent": ["dependency_dag_1:task_1", "dependency_dag_2:task_2"]
        }

        Returns a list of all static DAGs.
        These are DAGs that are not scheduled and don't have any dependencies that are scheduled, so they would not be triggered
        either by Airflow schedule nor Mediator.
        """

        non_scheduled_dags = self.find_all_non_scheduled_dags()
        return [
            dag_name
            for dag_name in non_scheduled_dags
            if DagBagService._is_static(dag_name, dependencies, non_scheduled_dags)
        ]

    @staticmethod
    def _is_static(dag_name: str, dependencies: dict, non_scheduled_dags: list) -> bool:
        """
        Internal method used to determine if a given DAG is static or not.
        These are DAGs that are not scheduled and don't have any dependencies that are scheduled, so they would not be triggered
        either by Airflow schedule nor Mediator.
        """
        if dag_name not in dependencies:
            return dag_name in non_scheduled_dags

        return all(
            [
                DagBagService._is_static(
                    dependency.split(":")[0], dependencies, non_scheduled_dags
                )
                for dependency in dependencies[dag_name]
            ]
        )

    def map_tables_to_correspondent_tasks_for_all_dags(self) -> dict:
        """
        Returns a dictionary in the following format, going through every DAG in the DagBag:
        {
            "<table name or database name>": [{
                "dag": "<name of the dag responsible for generating the table or database>"
                "full_task_name": <full task name responsible for generating the database. Comes in the format dag_id:task_id>
            }]
        }
        Note that the value is a list, since a table can be generated by more than one DAG.

        In order to find this, we look at the task that syncs with hive metastore (nearly all of our tables do it right after loading to Databricks).
        Specifically, the parameters sent to this task.
        """
        mapping = {}
        for dag in self.dag_bag.dags.values():
            DagBagService._add_tables_in_dag_to_task_mapping(mapping, dag)
        return mapping

    @staticmethod
    def _add_tables_in_dag_to_task_mapping(mapping: dict, dag: DAG) -> None:
        """
        Given a dictionary and a DAG, goes through each task to find one that is responsible for loading a table to Databricks, and adds that
        information to the mapping dictionary in the format
        {
            "<table name or database name>": [{
                "dag": "<name of the dag responsible for generating the table or database>"
                "full_task_name": <full task name responsible for generating the database. Comes in the format dag_id:task_id>
            }]
        }
        Note that the value is a list, since a table can be generated by more than one DAG.
        """
        if "create-cluster" not in dag.task_ids:
            return
        for task in dag.tasks:
            if not DagBagService._is_task_with_python_spark_job(task):
                continue
            if not task.json["spark_python_task"]["python_file"].endswith(
                "sync_metadata.py"
            ):
                continue
            DagBagService._add_table_in_sync_hive_task_to_mapping(mapping, task, dag)

    @staticmethod
    def _add_table_in_sync_hive_task_to_mapping(
        mapping: dict, sync_hive_structure_task: BaseOperator, dag: DAG
    ) -> None:
        """
            Given a sync with hive task, extracts the parameters and adds a key-value pair to the mapping dictionary,
            in the following format:
            {
                "<table name or database name>": [{
                    "dag": "<name of the dag responsible for generating the table or database>"
                    "full_task_name": <full task name responsible for generating the database. Comes in the format dag_id:task_id>
                }]
            }
            Note that the value is a list, since a table can be generated by more than one DAG.

            The full task_name is actually the task upstream from the hive sync, since it is the one responsible for loading
            to Databricks.

            If there is a correspondent Done task in the DAG, ":load-" will be replaced with ":done-"
            """
        upstream_task_id = sync_hive_structure_task.upstream_list[0].task_id
        params = sync_hive_structure_task.json["spark_python_task"]["parameters"]
        layer = LayerEnum(params[1])
        db_name_part = params[2]
        sync_mode = params[3]
        if sync_mode == "--table-name":
            table_name = params[4]
        else:
            table_name = None

        metastore_mapper = MetastoreMappingFactory.get_mapper_by_layer(
            layer=layer, source=db_name_part, bucket=""
        )
        spark_database_name = metastore_mapper.get_full_database_name(layer)
        full_table_name = (
            f"{spark_database_name}.{table_name}" if table_name else spark_database_name
        ).lower()

        # A done task is sometimes used instead of a load task, particularly for DAGs that eventually skip tasks (i.e., gsheets)
        done_task_id = upstream_task_id.replace("load-", "done-")
        has_correspondent_done_task = done_task_id in dag.task_ids
        if has_correspondent_done_task:
            dependency_task_name = done_task_id
        else:
            dependency_task_name = upstream_task_id

        if full_table_name not in mapping:
            mapping[full_table_name] = []
        mapping[full_table_name].append(
            {
                "dag": dag.dag_id,
                "full_task_name": f"{dag.dag_id}:{dependency_task_name}",
            }
        )

    def find_query_paths_by_load_task_for_all_dags(
        self, base_spark_jobs_path: str = "", base_dags_path: str = ""
    ) -> dict:
        """
        Given the base path of spark jobs, and the base path of all dags, returns a dictionary in which each
        key is a DAG name, and the value is a list of query paths associated with it.

        In order to do that, the parameters are extracted from tasks that have any of these spark jobs:
        - load_table_full.py
        - load_table_incremental.py
        - load_full_table_to_dw_staging_schema.py
        - load_incremental_table_to_dw_staging_schema.py
        - load_reverse_table_full.py
        - load_reverse_table_incremental.py
        """
        query_paths = {}
        for dag_name, dag in self.dag_bag.dags.items():
            query_paths[dag_name] = self.find_query_paths_by_load_task(
                dag, base_spark_jobs_path, base_dags_path
            )
        return query_paths

    @staticmethod
    def find_query_paths_by_load_task(
        dag: DAG, base_spark_jobs_path: str = "", base_dags_path: str = ""
    ) -> list:
        """
        For a given DAG, base spark jobs path and base dags path, returns a list of query paths associated with it.
        """
        query_paths = []
        dag_owner_path = dag.filepath.split("/")[1]
        for task in dag.tasks:
            query_path = DagBagService._extract_query_path_from_task(
                base_spark_jobs_path, task
            )
            if query_path is None:
                continue
            query_paths.append(f"{base_dags_path}/{dag_owner_path}/{query_path}")
        return query_paths

    @staticmethod
    def _extract_query_path_from_task(
        base_spark_jobs_path: str, task: BaseOperator
    ) -> str:
        """
        Given the base spark jobs path and an Airflow task, returns a query path if any is associated with it.
        Otherwise, returns None.
        """
        extraction_functions = {
            base_spark_jobs_path
            + "load_table_full.py": DagBagService._extract_query_path_from_datalake_task_parameters,
            base_spark_jobs_path
            + "load_table_incremental.py": DagBagService._extract_query_path_from_datalake_task_parameters,
            base_spark_jobs_path
            + "load_full_table_to_dw_staging_schema.py": DagBagService._extract_query_path_from_full_dw_staging_task_parameters,
            base_spark_jobs_path
            + "load_incremental_table_to_dw_staging_schema.py": DagBagService._extract_query_path_from_incremental_dw_staging_task_parameters,
            base_spark_jobs_path
            + "load_reverse_table_full.py": DagBagService._extract_query_path_from_datalake_task_parameters,
            base_spark_jobs_path
            + "load_reverse_table_incremental.py": DagBagService._extract_query_path_from_datalake_task_parameters,
        }
        if not DagBagService._is_task_with_python_spark_job(task):
            return None
        spark_job_name = task.json["spark_python_task"]["python_file"].replace(
            "//", "/"
        )
        if spark_job_name not in extraction_functions:
            return None

        return extraction_functions[spark_job_name](
            task.json["spark_python_task"]["parameters"]
        )

    @staticmethod
    def _is_task_with_python_spark_job(task: BaseOperator) -> bool:
        """Returns True if the task submits a python Spark Job to a Databricks Cluster"""
        if not hasattr(task, "json"):
            return False
        if "spark_python_task" not in task.json:
            False
        if "python_file" not in task.json["spark_python_task"]:
            return False
        return True

    @staticmethod
    def _extract_query_path_from_datalake_task_parameters(
        task_parameters: list,
    ) -> dict:
        """Given the list of parameters passed to a datalake load task, returns the formatted query path"""
        relative_query_path = task_parameters[5]
        layer = task_parameters[2]
        schema = task_parameters[11]
        tree_path = task_parameters[12]
        intermediate_path = schema if schema else tree_path
        table_name = task_parameters[6]
        return DagBagService._format_query_path_from_task_parameters(
            relative_query_path, layer, intermediate_path, table_name
        )

    @staticmethod
    def _extract_query_path_from_full_dw_staging_task_parameters(
        task_parameters: list,
    ) -> dict:
        """Given the list of parameters passed to a dw staging full load task, returns the formatted query path"""
        relative_query_path = task_parameters[3]
        layer = "dw"
        intermediate_path = task_parameters[6]
        table_name = task_parameters[4]
        return DagBagService._format_query_path_from_task_parameters(
            relative_query_path, layer, intermediate_path, table_name
        )

    @staticmethod
    def _extract_query_path_from_incremental_dw_staging_task_parameters(
        task_parameters: list,
    ) -> dict:
        """Given the list of parameters passed to a dw staging incremental load task, returns the formatted query path"""
        relative_query_path = task_parameters[3]
        layer = "dw"
        intermediate_path = task_parameters[9]
        table_name = task_parameters[4]
        return DagBagService._format_query_path_from_task_parameters(
            relative_query_path, layer, intermediate_path, table_name
        )

    @staticmethod
    def _format_query_path_from_task_parameters(
        relative_query_path: str, layer: str, intermediate_path: str, table_name: str
    ) -> str:
        """
        Given the relative query path, layer, intermediate path and table name, returns the expected path of the query
        (i.e., <relative_query_path>/queries/<layer>/<intermediate_path, if there is any>/<table_name>.sql')
        """
        return f"{relative_query_path}/queries/{layer}/{intermediate_path}/{table_name}.sql".replace(
            "//", "/"
        )
