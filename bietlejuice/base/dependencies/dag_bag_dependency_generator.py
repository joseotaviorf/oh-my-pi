from bietlejuice.base.dependencies.dependency_generator import DependencyGenerator
from bietlejuice.services.dag_bag_service import DagBagService

from quintoandar_logger import QuintoAndarLogger

logger = QuintoAndarLogger("DagBagDependencyGenerator")


class DagBagDependencyGenerator(DependencyGenerator):
    def __init__(
        self,
        dag_bag_service: DagBagService,
        base_spark_jobs_path: str,
        base_dags_path: str,
    ) -> None:
        """
        :param dag_bag_service: A service to access DAGs
        :type dag_bag_service: DagBagService
        :param base_spark_jobs_path: The base path for spark jobs
        :type base_spark_jobs_path: str
        :param base_dags_path: The base path for DAGs
        :type base_dags_path: str
        """
        super().__init__()
        self.dag_bag_service = dag_bag_service
        self.base_spark_jobs_path = base_spark_jobs_path
        self.base_dags_path = base_dags_path

    def map_tables_to_correspondent_tasks(self) -> dict:
        """
        Returns a dictionary in the following format, containing informations from all DAGs:
        {
            "<table name or database name>": [{
                "dag": "<name of the dag responsible for generating the table or database>"
                "full_task_name": <full task name responsible for generating the database. Comes in the format dag_id:task_id>
            }]
        }
        Note that the value is supposed to be a list, since sometimes a table is generated by more than one DAG.

        :return: A dictionary mapping tables to the DAGs and tasks that generate them
        :rtype: dict
        """
        logger.info(
            "m=map_tables_to_correspondent_tasks, msg=getting tasks that generated all tables"
        )
        return self.dag_bag_service.map_tables_to_correspondent_tasks_for_all_dags()

    def table_dependencies_from_all_dags(self) -> dict:
        """
        Map tables that are used in each DAG.
        e.g.:
        dict = {
            dag_1: [table_a, table_b, table_c],
            dag_2: [table_d, table_e, table_f]
        }
        :return: A dictionary mapping DAGs to tables used in their queries
        :rtype: dict
        """
        logger.info(
            "m=table_dependencies_from_all_dags, msg=getting table dependencies from all DAGs"
        )
        dags_queries_paths = (
            self.dag_bag_service.find_query_paths_by_load_task_for_all_dags(
                self.base_spark_jobs_path, self.base_dags_path
            )
        )
        dags_tables_dependencies = self._find_all_tables_in_query_files(
            dags_queries_paths
        )
        return dags_tables_dependencies

    def treat_exceptions(self, dependencies: dict) -> dict:
        """
        Method to treat exceptions from dependencies.
        e.g.:cyclic dependency and non-static DAG depending on a static DAG
        :param dependencies: A dictionary, in which keys are DAGs and values are lists of tasks
        :type dependencies: dict
        :return: A dictionary, in which keys are DAGs and values are lists of tasks, without cyclic dependencies or non-static DAGs depending on static DAGs.
        :rtype: dict
        """
        logger.info("m=treat_exceptions, msg=treating dependencies exceptions")
        static_dags = self.dag_bag_service.find_all_static_dags(dependencies)
        dependencies = self._remove_static_dependencies_in_non_static_dags(
            dependencies, static_dags
        )
        logger.info(
            "m=treat_exceptions, msg=dependencies exceptions successfully treated."
        )
        dependencies = self._remove_cyclic_dependencies(dependencies)
        return dependencies
