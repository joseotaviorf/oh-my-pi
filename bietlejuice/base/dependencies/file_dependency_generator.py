import re
from typing import List, Optional, Tuple
from collections import defaultdict

from bietlejuice.base.airflow.base_task_group import BaseTaskGroup
from bietlejuice.base.db.metastore_mapping_factory import MetastoreMappingFactory
from bietlejuice.base.dependencies.dependency_generator import DependencyGenerator
from bietlejuice.base.pipeline import LayerEnum
from bietlejuice.base.service.dag_packages_path_service import DAGPackagesPathService
from bietlejuice.formatters import StringFormatter
from bietlejuice.services.file_service import FileService

from dags import DAG_PACKAGES_ROOT

from quintoandar_logger import QuintoAndarLogger

logger = QuintoAndarLogger("FileDependencyGenerator")


class FileDependencyGenerator(DependencyGenerator):
    def __init__(self, unstandard_dags: dict = None) -> None:
        """
        Builds the FileDependencyGenerator object.

        :param unstandard_dags: A dict with the unstandard dags. Here is an example, with all accepted keys:
            {
                "bietlejuice.static_dag_name": {
                    "is_static": True,
                },
                "bietlejuice.dag_with_custom_task_name": {
                    "is_static": False,
                    "custom_task_names": [
                        {
                            "task_name": "load-{slugged_layer}-{slugged_schema}-{slugged_table_name}-custom",
                            "table_name_condition_regex": ".*",
                        }
                    ]
                },
            }
            The "is_static" key is optional and defaults to False. It is relevant because we need to remove static dependencies from
            DAGs that are not static.

            The "custom_task_names" key is optional and defaults to an empty list. It is relevant when the load task has a custom name, outside
            of the default specified in BaseTaskGroup. Inside it, it will be a list of dicts, each one with the following keys:
                - task_name: The custom task name. It can have the following placeholders:
                    - {slugged_layer}: The layer name.
                    - {slugged_schema}: The schema name, slugged.
                    - {slugged_table_name}: The table name, slugged.
                - table_name_condition_regex: A regex to match the table name. If it matches, the custom task name will be used. Otherwise,
                    the default task name will be used.
        :type unstandard_dags: dict

        :return: None
        """
        super().__init__()
        self.metastore_mapping_factory = MetastoreMappingFactory()
        self.unstandard_dags = unstandard_dags or {}

    def map_tables_to_correspondent_tasks(self) -> dict:
        """
        Returns a dictionary in the following format, containing informations from all DAGs:
        {
            "<table name or database name>": [{
                "dag": "<name of the dag responsible for generating the table or database>"
                "full_task_name": <full task name responsible for generating the database. Comes in the format dag_id:task_id>
            }]
        }
        In order to do that, this method will get the tables from the metadata files, and the DAG name from their path.

        Note that the value is supposed to be a list, since sometimes a table is generated by more than one DAG.
        """
        mapping = defaultdict(list)
        metadata_files = self._get_metadata_files()
        for path in metadata_files:
            (
                dag,
                layer,
                database_name,
                table_name,
            ) = self._get_dag_and_table_from_metadata_path(path)
            task_name = self._get_task_name_from_table_name(
                dag, database_name, table_name, layer
            )
            full_table_name = f"{database_name}.{table_name}"
            mapping[full_table_name].append(
                {"dag": dag, "full_task_name": f"{dag}:{task_name}"}
            )

        return mapping

    def _get_metadata_files(self) -> List[str]:
        return DAGPackagesPathService.list_artifact_file_paths("metadata", "**", "*")

    def _get_path_without_base_or_owner(self, full_path: str) -> str:
        path_without_base = full_path.replace(DAG_PACKAGES_ROOT + "/", "")
        path_without_owner = "/".join(path_without_base.split("/")[1:])
        return path_without_owner

    def _get_dag_and_table_from_metadata_path(
        self, path: str
    ) -> Tuple[str, str, str, str]:
        """Returns the dag name, layer, database name and task name from a metadata path."""
        _, layer, _, dag, _, _ = FileService.get_table_info_from_path(
            self._get_path_without_base_or_owner(path)
        )
        metadata_content = FileService.get_dict_from_yaml_file(path)
        database_name = metadata_content["database_name"]
        table_name = metadata_content["table_name"]

        return dag, layer, database_name, table_name

    def _get_task_name_from_table_name(
        self, dag: str, database_name: str, table_name: str, layer: str
    ) -> str:
        """If the dag is unstandard, returns the custom task name. Otherwise, returns the default task name."""

        layer_enum = LayerEnum(layer)
        schema = self._get_schema_from_database_name(layer_enum, database_name)
        unstandard_task_name = self._get_unstandard_task_name(
            dag, schema, table_name, layer
        )
        if unstandard_task_name:
            return unstandard_task_name

        return BaseTaskGroup.generate_default_task_id(
            task_prefix=BaseTaskGroup.LOAD_TASK_PREFIX,
            layer=layer_enum,
            schema=schema,
            table_name=table_name,
        )

    def _get_schema_from_database_name(
        self, layer_enum: LayerEnum, database_name: str
    ) -> str:
        return self.metastore_mapping_factory.get_mapper_by_layer(
            layer=layer_enum, source=database_name, bucket=""
        ).get_schema_from_database(database_name)

    def _get_unstandard_task_name(
        self, dag: str, schema: str, table_name: str, layer: str
    ) -> Optional[str]:
        if dag not in self.unstandard_dags:
            return None
        if "custom_task_names" not in self.unstandard_dags[dag]:
            return None

        custom_tasks = self.unstandard_dags[dag]["custom_task_names"]
        for custom_task in custom_tasks:
            table_name_matches_regex = re.match(
                custom_task["table_name_condition_regex"], table_name
            )
            if table_name_matches_regex:
                return self._apply_place_holders_to_task_name(
                    custom_task["task_name"], schema, table_name, layer
                )

    def _apply_place_holders_to_task_name(
        self, task_name: str, schema: str, table_name: str, layer: str
    ) -> str:
        return (
            task_name.replace("{slugged_schema}", StringFormatter.slugify(schema))
            .replace("{slugged_table_name}", StringFormatter.slugify(table_name))
            .replace("{slugged_layer}", StringFormatter.slugify(layer))
        )

    def table_dependencies_from_all_dags(self) -> dict:
        """
        Map tables that are used in each DAG.
        e.g.:
        dict = {
            dag_1: [table_a, table_b, table_c],
            dag_2: [table_d, table_e, table_f]
        }
        In order to do that, this method will get the tables from the query files, and the DAG name from their path.

        :return: A dictionary mapping DAGs to tables used in their queries
        :rtype: dict
        """

        query_files = self._get_query_files()
        dags_query_paths = defaultdict(list)
        for path in query_files:
            _, _, _, dag, _, _ = FileService.get_table_info_from_path(
                self._get_path_without_base_or_owner(path)
            )
            dags_query_paths[dag].append(path)
        return self._find_all_tables_in_query_files(dags_query_paths)

    def _get_query_files(self) -> List[str]:
        return DAGPackagesPathService.list_artifact_file_paths("query", "**", "*")

    def treat_exceptions(self, dependencies: dict) -> dict:
        """
        Method to treat exceptions from dependencies.
        e.g.:cyclic dependency and non-static DAG depending on a static DAG
        :param dependencies: A dictionary, in which keys are DAGs and values are lists of tasks
        :type dependencies: dict
        :return: A dictionary, in which keys are DAGs and values are lists of tasks, without cyclic dependencies or non-static DAGs depending on static DAGs.
        :rtype: dict
        """
        logger.info("m=treat_exceptions, msg=treating dependencies exceptions")
        static_dags = [
            dag_name
            for dag_name, dag in self.unstandard_dags.items()
            if dag.get("is_static")
        ]
        dependencies = self._remove_static_dependencies_in_non_static_dags(
            dependencies, static_dags
        )
        logger.info(
            "m=treat_exceptions, msg=dependencies exceptions successfully treated."
        )
        dependencies = self._remove_cyclic_dependencies(dependencies)
        return dependencies
